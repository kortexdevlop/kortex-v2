//! Headless engine build (ADR 0035): one `engine.wasm` per tool, ABI v1, no `wasm-bindgen`.
//!
//! A throwaway crate in `.kortex/engine-src/<id>/` links the tool with `kortex-runtime` (feature
//! `engine-abi`) and exports the ABI with one macro line; the result is optimised with
//! `wasm-opt` when it is installed. The same file serves the web, the desktop players, Flow, Mind
//! and the CLI.
use crate::fwd;
use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

/// Writes the throwaway engine crate of `id` and returns its directory. The crate holds the wasm
/// library (`export_engine!`) and a native `native` binary that serves the same frames on
/// stdin/stdout, the reference of `cargo xtask engines-check`.
fn write_sources(root: &Path, tool_dir: &Path, id: &str) -> Result<PathBuf, String> {
    let work = root.join(".kortex/engine-src").join(id);
    fs::create_dir_all(work.join("src/bin")).map_err(|e| e.to_string())?;
    let slug = id.replace('.', "-");
    let manifest = format!(
        r#"[package]
name = "engine-{slug}"
version = "0.0.0"
edition = "2024"
[lib]
crate-type = ["cdylib"]
[[bin]]
name = "native"
path = "src/bin/native.rs"
[dependencies]
tool = {{ package = "tool-{slug}", path = {:?} }}
kortex-runtime = {{ path = {:?}, features = ["engine-abi"] }}
[workspace]
[profile.release]
opt-level = "z"
lto = true
codegen-units = 1
panic = "abort"
strip = true
"#,
        fwd(tool_dir),
        fwd(&root.join("crates/kortex-runtime"))
    );
    fs::write(work.join("Cargo.toml"), manifest).map_err(|e| e.to_string())?;
    if !work.join("Cargo.lock").exists() {
        fs::copy(root.join("Cargo.lock"), work.join("Cargo.lock")).map_err(|e| e.to_string())?;
    }
    fs::write(
        work.join("src/lib.rs"),
        "// GENERATED by `cargo xtask build-engine` — do not edit.\nkortex_runtime::export_engine!(tool::run_map);\n",
    )
    .map_err(|e| e.to_string())?;
    fs::write(
        work.join("src/bin/native.rs"),
        r#"// GENERATED by `cargo xtask build-engine` — do not edit.
use std::io::{Read, Write};

fn main() {
    let mut request = Vec::new();
    if std::io::stdin().read_to_end(&mut request).is_err() {
        std::process::exit(2);
    }
    let response = kortex_runtime::engine_abi::handle(&request, |inputs, params, cx| {
        kortex_runtime::block_on(tool::run_map(inputs, params, cx))
    });
    if std::io::stdout().write_all(&response).is_err() {
        std::process::exit(2);
    }
}
"#,
    )
    .map_err(|e| e.to_string())?;
    Ok(work)
}

/// Builds the native reference binary of `id` (same engine, same frames, no wasm).
pub fn build_native(root: &Path, tool_dir: &Path, id: &str) -> Result<PathBuf, String> {
    let work = write_sources(root, tool_dir, id)?;
    let target = root.join(".kortex/target-engine-native");
    let status = Command::new("cargo")
        .args(["build", "--release", "--bin", "native"])
        .current_dir(&work)
        .env("CARGO_TARGET_DIR", &target)
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err(format!("compilation native du moteur échouée : {id}"));
    }
    Ok(target.join("release").join(if cfg!(windows) {
        "native.exe"
    } else {
        "native"
    }))
}

/// Builds the engine of `id` and returns the path of its `engine.wasm`.
pub fn build(root: &Path, tool_dir: &Path, id: &str) -> Result<PathBuf, String> {
    let work = write_sources(root, tool_dir, id)?;
    let slug = id.replace('.', "-");
    let target = root.join(".kortex/target-worker");
    let status = Command::new("cargo")
        .args([
            "build",
            "--release",
            "--lib",
            "--target",
            "wasm32-unknown-unknown",
        ])
        .current_dir(&work)
        .env("CARGO_TARGET_DIR", &target)
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err(format!("compilation du moteur échouée : {id}"));
    }
    let built = target
        .join("wasm32-unknown-unknown/release")
        .join(format!("engine_{}.wasm", slug.replace('-', "_")));
    let out = root.join(".kortex/engines").join(id).join("engine.wasm");
    fs::create_dir_all(out.parent().ok_or("chemin invalide")?).map_err(|e| e.to_string())?;
    // `wasm-opt` is optional locally (the CI image has it): without it the engine is bigger, not
    // different. The features are the ones rustc enables by default for wasm32.
    let optimised = Command::new("wasm-opt")
        .args([
            "-Oz",
            "--enable-bulk-memory",
            "--enable-sign-ext",
            "--enable-mutable-globals",
            "--enable-nontrapping-float-to-int",
            "--enable-multivalue",
            "--enable-reference-types",
        ])
        .arg(&built)
        .arg("-o")
        .arg(&out)
        .status()
        .is_ok_and(|s| s.success());
    if !optimised {
        fs::copy(&built, &out).map_err(|e| format!("{} : {e}", built.display()))?;
    }
    Ok(out)
}

/// `cargo xtask build-engine <univers.nom… | all>`: the headless `engine.wasm` of any tool
/// (MASTER_PROMPT §7.3), written to `dist/engines/<id>/engine.wasm`. A receipt (source
/// fingerprint + output hash) skips identical rebuilds.
pub fn build_engine(args: &[String]) -> Result<(), String> {
    let root = std::env::current_dir().map_err(|e| e.to_string())?;
    let wanted: Vec<&String> = args.iter().collect();
    if wanted.is_empty() {
        return Err("usage : cargo xtask build-engine <univers.nom… | all>".to_owned());
    }
    let all = wanted.iter().any(|a| a.as_str() == "all");
    let mut built = 0_usize;
    for tool in crate::tools::discover()? {
        let contract = tool
            .contract
            .map_err(|e| format!("{} : {e}", tool.dir.display()))?;
        let id = contract.tool.id;
        if !all && !wanted.iter().any(|w| **w == id) {
            continue;
        }
        let tool_dir = root.join(&tool.dir);
        let dest = root.join("dist/engines").join(&id);
        let receipt = root.join(".kortex/engines").join(&id).join("receipt.json");
        let source = crate::build::engine_fingerprint(&root, &tool_dir)?;
        if dest.is_dir()
            && let Ok(previous) = fs::read_to_string(&receipt)
        {
            let current = serde_json::json!({"source": source, "output": crate::build::tree_fingerprint(&dest)?})
                .to_string();
            if previous == current {
                println!("✓ dist/engines/{id}/ à jour (compilation évitée)");
                built += 1;
                continue;
            }
        }
        let wasm = build(&root, &tool_dir, &id)?;
        let _ = fs::remove_dir_all(&dest);
        fs::create_dir_all(&dest).map_err(|e| e.to_string())?;
        fs::copy(&wasm, dest.join("engine.wasm")).map_err(|e| format!("{id} : {e}"))?;
        let bytes = fs::read(dest.join("engine.wasm")).map_err(|e| e.to_string())?;
        // Loading the module proves it exports the whole ABI; imports outside `kx_host` are
        // reported because the hosts stub them (they fail if an engine ever calls them).
        let module = kortex_engine_host::EngineModule::load(&bytes)
            .map_err(|e| format!("{id} : moteur invalide : {e}"))?;
        let foreign = module.foreign_imports();
        if let Some(parent) = receipt.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        fs::write(
            &receipt,
            serde_json::json!({"source": source, "output": crate::build::tree_fingerprint(&dest)?})
                .to_string(),
        )
        .map_err(|e| e.to_string())?;
        println!(
            "✓ dist/engines/{id}/engine.wasm ({} Ko, {} import(s) hors kx_host)",
            bytes.len() / 1024,
            foreign.len()
        );
        built += 1;
    }
    if built == 0 {
        return Err("aucun outil correspondant".to_owned());
    }
    Ok(())
}
