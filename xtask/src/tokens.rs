//! `design/tokens/*.toml` + `design/components.css` -> `design/dist/kortex.css`.
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use toml::{Table, Value};

fn read_table(path: &Path) -> Result<Table, String> {
    let text =
        fs::read_to_string(path).map_err(|e| format!("{} illisible : {e}", path.display()))?;
    text.parse::<Table>()
        .map_err(|e| format!("{} invalide : {e}", path.display()))
}

fn declarations(prefix: &str, table: &Table) -> Result<String, String> {
    let mut out = String::new();
    for (key, value) in table {
        let Value::String(v) = value else {
            return Err(format!("token `{prefix}{key}` doit être une chaîne"));
        };
        let _ = writeln!(out, "  --k-{prefix}{key}: {v};");
    }
    Ok(out)
}

/// Standard (RFC 4648) base64 with padding, for embedding binary assets in generated CSS.
fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let n = chunk
            .iter()
            .enumerate()
            .fold(0_u32, |acc, (i, b)| acc | (u32::from(*b) << (16 - 8 * i)));
        for i in 0..4 {
            if i <= chunk.len() {
                out.push(char::from(ALPHABET[((n >> (18 - 6 * i)) & 63) as usize]));
            } else {
                out.push('=');
            }
        }
    }
    out
}

/// `@font-face` for the self-hosted Inter Variable (latin subset), embedded as a data URI.
fn font_face(path: &Path) -> Result<String, String> {
    let bytes = fs::read(path).map_err(|e| format!("{} illisible : {e}", path.display()))?;
    if !bytes.starts_with(b"wOF2") {
        return Err(format!("{} n'est pas un fichier woff2", path.display()));
    }
    Ok(format!(
        "@font-face {{\n  font-family: 'Inter Variable';\n  font-style: normal;\n  font-display: swap;\n  font-weight: 100 900;\n  src: url(data:font/woff2;base64,{}) format('woff2-variations');\n  unicode-range: U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD;\n}}\n",
        base64(&bytes)
    ))
}

pub fn run() -> Result<(), String> {
    let dir = Path::new("design/tokens");
    let mut root = String::new();
    for name in ["space", "radius", "shadow", "motion", "type", "glass"] {
        let t = read_table(&dir.join(format!("{name}.toml")))?;
        root.push_str(&declarations(&format!("{name}-"), &t)?);
    }
    let colors = read_table(&dir.join("colors.toml"))?;
    let theme = |name: &str| -> Result<String, String> {
        match colors.get(name) {
            Some(Value::Table(t)) => declarations("", t),
            _ => Err(format!("colors.toml : table [{name}] manquante")),
        }
    };
    let (light, dark) = (theme("light")?, theme("dark")?);
    let indent = |s: &str| s.lines().map(|l| format!("  {l}\n")).collect::<String>();

    let mut css = String::from("/* GENERATED by `cargo xtask tokens` — do not edit. */\n");
    css.push_str(&font_face(Path::new(
        "design/fonts/inter-latin-wght-normal.woff2",
    ))?);
    let _ = write!(css, ":root {{\n{root}{light}}}\n");
    let _ = write!(
        css,
        "@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{}  }}\n}}\n",
        indent(&dark)
    );
    let _ = write!(css, ":root[data-theme=\"dark\"] {{\n{dark}}}\n\n");
    css.push_str(
        &fs::read_to_string("design/components.css")
            .map_err(|e| format!("components.css : {e}"))?,
    );

    fs::create_dir_all("design/dist").map_err(|e| e.to_string())?;
    fs::write("design/dist/kortex.css", css).map_err(|e| e.to_string())?;
    println!("✓ design/dist/kortex.css généré");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::base64;

    #[test]
    fn base64_matches_rfc_4648_vectors() {
        for (input, expected) in [
            ("", ""),
            ("f", "Zg=="),
            ("fo", "Zm8="),
            ("foo", "Zm9v"),
            ("foob", "Zm9vYg=="),
            ("fooba", "Zm9vYmE="),
            ("foobar", "Zm9vYmFy"),
        ] {
            assert_eq!(base64(input.as_bytes()), expected, "{input:?}");
        }
        assert_eq!(base64(&[0xFB, 0xFF, 0xBF]), "+/+/");
    }

    #[test]
    fn embedded_font_is_a_woff2_data_uri_for_the_token_family() {
        let face = super::font_face(std::path::Path::new(
            "../design/fonts/inter-latin-wght-normal.woff2",
        ))
        .unwrap_or_else(|e| unreachable!("{e}"));
        assert!(face.contains("font-family: 'Inter Variable'"));
        assert!(
            face.contains("src: url(data:font/woff2;base64,d09GMg"),
            "wOF2 magic in base64"
        );
        assert!(face.contains("font-weight: 100 900"));
    }
}
