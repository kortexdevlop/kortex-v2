//! `design/tokens/*.toml` + `design/components.css` -> `design/dist/kortex.css`.
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use toml::{Table, Value};

fn read_table(path: &Path) -> Result<Table, String> {
    let text =
        fs::read_to_string(path).map_err(|e| format!("{} illisible : {e}", path.display()))?;
    text.parse::<Table>()
        .map_err(|e| format!("{} invalide : {e}", path.display()))
}

fn declarations(prefix: &str, table: &Table) -> Result<String, String> {
    let mut out = String::new();
    for (key, value) in table {
        let Value::String(v) = value else {
            return Err(format!("token `{prefix}{key}` doit être une chaîne"));
        };
        let _ = writeln!(out, "  --k-{prefix}{key}: {v};");
    }
    Ok(out)
}

pub fn run() -> Result<(), String> {
    let dir = Path::new("design/tokens");
    let mut root = String::new();
    for name in ["space", "radius", "shadow", "motion", "type"] {
        let t = read_table(&dir.join(format!("{name}.toml")))?;
        root.push_str(&declarations(&format!("{name}-"), &t)?);
    }
    let colors = read_table(&dir.join("colors.toml"))?;
    let theme = |name: &str| -> Result<String, String> {
        match colors.get(name) {
            Some(Value::Table(t)) => declarations("", t),
            _ => Err(format!("colors.toml : table [{name}] manquante")),
        }
    };
    let (light, dark) = (theme("light")?, theme("dark")?);
    let indent = |s: &str| s.lines().map(|l| format!("  {l}\n")).collect::<String>();

    let mut css = String::from("/* GENERATED by `cargo xtask tokens` — do not edit. */\n");
    let _ = write!(css, ":root {{\n{root}{light}}}\n");
    let _ = write!(
        css,
        "@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{}  }}\n}}\n",
        indent(&dark)
    );
    let _ = write!(css, ":root[data-theme=\"dark\"] {{\n{dark}}}\n\n");
    css.push_str(
        &fs::read_to_string("design/components.css")
            .map_err(|e| format!("components.css : {e}"))?,
    );

    fs::create_dir_all("design/dist").map_err(|e| e.to_string())?;
    fs::write("design/dist/kortex.css", css).map_err(|e| e.to_string())?;
    println!("✓ design/dist/kortex.css généré");
    Ok(())
}
