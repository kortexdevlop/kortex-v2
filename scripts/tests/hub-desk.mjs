 await page.locator('[data-widget="favorites"][data-wide="true"]').waitFor();
 assert.equal(await page.locator('[data-widget="favorites"] [data-tool]').count(),1);
 await page.getByRole('searchbox').fill('hash');
 assert.equal(await page.locator('[data-widget="catalogue"] [data-tool]').count(),1);
 await page.locator('[data-widget="catalogue"] [data-tool="secure.hash-calculator"]').getByRole('link',{name:'Ouvrir',exact:true}).click();
 await page.waitForURL(/workspace.*tool=secure.hash-calculator/);
 const window=page.locator('.desk-window').first();
 await window.waitFor();
 assert.ok(await page.evaluate(()=>Object.values(localStorage).some(value=>{try{return JSON.parse(value).windows?.some(window=>window.tool==='secure.hash-calculator');}catch{return false;}})),'query-launched window is saved before any interaction');
 const firstFrame=page.frameLocator('.desk-window iframe').first();
 const hash='ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad';
 await firstFrame.getByLabel('Texte (si aucun fichier)',{exact:true}).fill('abc');
 await firstFrame.getByRole('button',{name:'Lancer',exact:true}).click();
 await firstFrame.getByText(hash,{exact:true}).waitFor();
 const before=await window.boundingBox();
