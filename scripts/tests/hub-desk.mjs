 const evidence={mode:published?'public HTTPS':'local delivery of compiled artifacts',date:new Date().toISOString(),results,errors};
 writeFileSync(resolve(root,`.kortex/qa/apps-${published?'public':'local'}.json`),JSON.stringify(evidence,null,2));
 console.log(JSON.stringify(evidence,null,2));
