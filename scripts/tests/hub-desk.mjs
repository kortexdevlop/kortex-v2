 await page.locator('.desk-window').first().waitFor();
 await page.screenshot({path:resolve(root,'.kortex/qa/desk-desktop.png'),fullPage:true});
 const blocked=await browser.newContext();
 await blocked.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Blocked','SecurityError');}}));
 // Storage denial is checked against the actual public app, where no delivery substitution is needed.
 if(published){const denied=await blocked.newPage();await denied.goto(url('hub'));await denied.getByRole('alert').filter({hasText:'La sauvegarde locale'}).waitFor();await denied.locator('[data-widget="catalogue"] [data-tool]').first().getByRole('button',{name:'Ajouter aux favoris'}).click();assert.equal(await denied.locator('[data-widget="favorites"] [data-tool]').count(),1);results.push('Blocked browser storage shows a clear warning; in-memory favourites remain usable.');}
