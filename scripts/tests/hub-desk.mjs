 if(!published) await context.route('https://*.kortex.site/**',async route=>{
  const url=new URL(route.request().url());
  const name=Object.keys(domains).find(k=>domains[k]===url.hostname);
  const base=name==='run'?resolve(root,'dist/run'):['hub','desk'].includes(name)?resolve(root,`dist/apps/apps.${name}`):null;
  if(!base)return route.abort();
  let path=resolve(base,'.'+decodeURIComponent(url.pathname));
  if(!path.startsWith(base+sep)&&path!==base)return route.abort();
  if(existsSync(path)&&statSync(path).isDirectory())path=resolve(path,'index.html');
  if(!existsSync(path))return route.fulfill({status:404,body:'Missing compiled artifact'});
  const mime={'.html':'text/html','.js':'text/javascript','.css':'text/css','.wasm':'application/wasm','.json':'application/json','.svg':'image/svg+xml','.woff2':'font/woff2'}[extname(path)]||'application/octet-stream';
  const csp=`default-src 'self'; script-src 'self' 'unsafe-inline' 'unsafe-eval' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self' https://${domains.api}; worker-src 'self'; frame-src https://${domains.run}; frame-ancestors https://${domains.root} https://${domains.desk} https://${domains.hub}; object-src 'none'; base-uri 'self'`;
  await route.fulfill({contentType:mime,body:readFileSync(path),headers:{'content-security-policy':csp}});
 });
 const page=await context.newPage(),errors=[];
